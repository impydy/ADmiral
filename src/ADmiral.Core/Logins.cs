using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;
using System.Text.Json.Serialization;
using System.Text.RegularExpressions;
using Microsoft.Extensions.Logging;

namespace ADmiral.Core;

/// <summary>Result of <see cref="Logins.ImportFolder"/> (field names as the UI expects).</summary>
public sealed class LoginImportResult
{
    [JsonPropertyName("configured")] public bool Configured { get; set; }
    [JsonPropertyName("found")] public int Found { get; set; }
    [JsonPropertyName("imported")] public int Imported { get; set; }
    [JsonPropertyName("unknown")] public int Unknown { get; set; }
    [JsonPropertyName("failed")] public int Failed { get; set; }
    /// <summary>Logons of local (non-domain) accounts: their files are deleted, nothing is stored.</summary>
    [JsonPropertyName("local")] public int Local { get; set; }
    [JsonPropertyName("error"), JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)] public string? Error { get; set; }
}

/// <summary>Login tracking (ported from admiral/logins.py): the fallback for the logon history when a computer's event
/// log cannot be read. A PowerShell script (generated here, run by Group Policy as a computer startup script) registers a
/// SYSTEM scheduled task that leaves one small JSON file per logon in a shared folder; ADmiral merges those entries into
/// the computers' logon history and deletes every file it has read.</summary>
public static partial class Logins
{
    public const string Suffix = ".log";
    public const string ScriptName = "ADmiral-Logins.ps1";
    public const int MaxBytes = 64 * 1024;

    private const string LoginsTemplate = """"
<#
.SYNOPSIS
  ADmiral login tracking: records who logs on to this computer and when, as a small log file in a shared folder.

.DESCRIPTION
  A fallback for computers whose event log ADmiral cannot read. Add it in Group Policy as a computer
  STARTUP script (Computer Configuration > Policies > Windows Settings > Scripts > Startup > PowerShell Scripts).

  What it does:
   * at startup: registers a scheduled task ("ADmiral-Logins", runs as SYSTEM at every logon) that carries
     this script itself (no copy on the disk) and runs it with -Log;
   * with -Log (the task): writes one file <COMPUTER>_<time>_<session>_<random>.log to the folder below for every
     new interactive / remote / cached logon session. Nothing else is changed or sent anywhere.

  ADmiral reads the files from that folder and deletes them afterwards.
  The folder needs 'Create files / write data' (this folder only) for the COMPUTER accounts (Domain Computers),
  because the task runs as SYSTEM. Nothing more: never give them modify or delete rights on the files.
  Generated by ADmiral - do not edit; save a fresh copy from ADmiral (Settings) after updates.

.PARAMETER OutputPath
  The shared folder the log files are written to (the one set in ADmiral's Settings).
#>
param(
  [string]$OutputPath = '@@PATH@@',
  [switch]$Log
)

$ErrorActionPreference = 'Stop'
$key = 'HKLM:\SOFTWARE\ADmiral\Logins'

if (-not $Log) {
  # The task carries this script (without its help text) as -EncodedCommand: nothing on the disk that a
  # user could replace and SYSTEM would then run.
  $self = (Get-Content -Raw -LiteralPath $PSCommandPath) -replace '(?s)<#.*?#>', ''
  $wrapped = '& {' + $self + '} -Log -OutputPath ''' + ($OutputPath -replace "'", "''") + ''''
  $enc = [Convert]::ToBase64String([Text.Encoding]::Unicode.GetBytes($wrapped))
  $arg = '-NoProfile -NonInteractive -ExecutionPolicy Bypass -WindowStyle Hidden -EncodedCommand ' + $enc
  $action = New-ScheduledTaskAction -Execute 'powershell.exe' -Argument $arg
  $trigger = New-ScheduledTaskTrigger -AtLogOn
  $principal = New-ScheduledTaskPrincipal -UserId 'SYSTEM' -LogonType ServiceAccount -RunLevel Highest
  Register-ScheduledTask -TaskName 'ADmiral-Logins' -Action $action -Trigger $trigger -Principal $principal -Force | Out-Null
  # files of ADmiral 0.5.1, which kept a copy of the script in ProgramData
  foreach ($old in 'ADmiral-Logins.ps1', 'logins-seen.txt') {
    Remove-Item -LiteralPath (Join-Path $env:ProgramData ('ADmiral\' + $old)) -Force -ErrorAction SilentlyContinue
  }
  exit 0
}

Start-Sleep -Seconds 5                       # let the session finish starting
if (-not (Test-Path $key)) { New-Item -Path $key -Force | Out-Null }
$seen = @((Get-ItemProperty -Path $key -Name Seen -ErrorAction SilentlyContinue).Seen | Where-Object { $_ })
$users = Get-CimInstance Win32_LoggedOnUser
$new = @()
foreach ($s in (Get-CimInstance Win32_LogonSession | Where-Object { $_.LogonType -in 2, 10, 11 })) {
  $id = [string]$s.LogonId
  if ($seen -contains $id) { continue }
  $a = $users | Where-Object { [string]$_.Dependent.LogonId -eq $id } | Select-Object -First 1
  if (-not $a) { continue }
  $user = [string]$a.Antecedent.Name; $domain = [string]$a.Antecedent.Domain
  $new += $id
  if (-not $user -or $user -match '\$$' -or $user -match '^(DWM|UMFD)-\d+$' -or $domain -in 'NT AUTHORITY', 'NT SERVICE', 'Window Manager', 'Font Driver Host') { continue }
  # local accounts of this computer (domain = computer name) are not tracked: nothing about them is written
  if ($domain -eq $env:COMPUTERNAME -or $domain -eq '.') { continue }
  $when = ([datetime]$s.StartTime).ToUniversalTime()
  $rec = [ordered]@{ computer = $env:COMPUTERNAME; time = $when.ToString('o'); user = $user; domain = $domain; type = [int]$s.LogonType; ip = '' }
  # written in place, no rename: the computers only need 'Create files / write data' on the folder. The file is
  # locked while it is written (ADmiral skips it until then) and the random part means nobody can plant it.
  $name = '{0}_{1}_{2}_{3}.log' -f $env:COMPUTERNAME, $when.ToString('yyyyMMddHHmmss'), $id, [guid]::NewGuid().ToString('N').Substring(0, 8)
  $bytes = (New-Object Text.UTF8Encoding $false).GetBytes(($rec | ConvertTo-Json -Compress))
  $fs = [IO.File]::Open((Join-Path $OutputPath $name), [IO.FileMode]::CreateNew, [IO.FileAccess]::Write, [IO.FileShare]::None)
  try { $fs.Write($bytes, 0, $bytes.Length) } finally { $fs.Dispose() }
}
if ($new.Count) {
  $keep = @((@($seen) + $new) | Select-Object -Last 300)
  New-ItemProperty -Path $key -Name Seen -PropertyType MultiString -Value $keep -Force | Out-Null
}
"""";

    /// <summary>The PowerShell script for the shared folder <paramref name="path"/> (the path is placed in a single-quoted
    /// literal, every single-quote character doubled; CRLF line ends).</summary>
    public static string RenderScript(string path) =>
        (LoginsTemplate + "\n").Replace("@@PATH@@", EscapeSingleQuoted(path ?? ""))
                               .Replace("\r\n", "\n").Replace("\n", "\r\n");

    private static string EscapeSingleQuoted(string s)
    {
        var q = Deploy.Q(s);
        return q[1..^1];
    }

    [GeneratedRegex(@"\A[\p{L}\p{N}_][\p{L}\p{N}_.-]{0,62}\z")]
    private static partial Regex ComputerName();

    /// <summary>(computer name, logon event) of one log file; <see cref="FormatException"/> for anything not valid.</summary>
    public static (string Computer, JsonObject Event) ParseEntry(byte[] raw)
    {
        if (raw.Length > MaxBytes) throw new FormatException("file too large");
        JsonNode? doc;
        try
        {
            doc = Collector.ParseJson(raw, 8);
        }
        catch (Exception exc) when (exc is JsonException or DecoderFallbackException or ArgumentException)
        {
            throw new FormatException($"not valid JSON: {exc.Message}", exc);
        }
        if (doc is not JsonObject obj) throw new FormatException("not a JSON object");
        var computer = (obj["computer"] is JsonValue v && v.GetValueKind() == JsonValueKind.String ? v.GetValue<string>() : "").Trim();
        if (!ComputerName().IsMatch(computer)) throw new FormatException("bad computer name");
        var events = CollectorModel.CleanLogons([obj]);
        if (events.Count == 0) throw new FormatException("not an interactive logon of a real user");
        return (computer, events[0]);
    }

    /// <summary>A logon of a local account of that computer (its domain is the computer name, or "."), not a domain user.</summary>
    public static bool IsLocalAccount(string computer, JsonObject ev)
    {
        var domain = ((string?)ev["domain"] ?? "").Trim();
        return domain == "." || string.Equals(domain, computer.Trim(), StringComparison.OrdinalIgnoreCase);
    }

    /// <summary>The files of the script before 0.6.2 (<c>&lt;computer&gt;_&lt;time&gt;_&lt;session&gt;.tmp</c>), left
    /// behind when renaming them to .log failed. Written in full before that rename, so they are read like the .log files
    /// (same checks) once they are older than <see cref="LegacyTempAge"/>.</summary>
    internal static IEnumerable<string> LegacyTemp(string folder, DateTime nowUtc) =>
        Inbox.List(folder, ".tmp").Where(p => LegacyTempName().IsMatch(Path.GetFileName(p))
                                               && nowUtc - File.GetLastWriteTimeUtc(p) >= LegacyTempAge);

    /// <summary>A left-over .tmp file younger than this may still be written by an old script.</summary>
    public static readonly TimeSpan LegacyTempAge = TimeSpan.FromMinutes(2);

    [GeneratedRegex(@"_\d{14}_\d+\.tmp\z", RegexOptions.IgnoreCase)]
    private static partial Regex LegacyTempName();

    /// <summary>A sharing violation: the script still has the file open.</summary>
    private static bool Busy(IOException exc) => (exc.HResult & 0xFFFF) is 32 or 33;

    /// <summary>Merge the logon files of the configured folder into the history and delete them. A file of a computer
    /// that is not in the list stays (it may be added later); an invalid or untrusted file is renamed to <c>*.bad</c> so it
    /// is neither read again nor lost.</summary>
    public static LoginImportResult ImportFolder(Store store, Settings settings, IFileSecurity? security = null)
    {
        var cfg = settings.Logins;
        var folder = (cfg.Path ?? "").Trim();
        var outp = new LoginImportResult { Configured = cfg.Enabled && folder.Length > 0 };
        if (!outp.Configured) return outp;
        List<string> files;
        try
        {
            files = Inbox.List(folder, Suffix);
            files.AddRange(LegacyTemp(folder, DateTime.UtcNow));
        }
        catch (Exception exc) when (exc is IOException or UnauthorizedAccessException or System.Security.SecurityException or ArgumentException)
        {
            Log.Logger.LogWarning("Login folder {Folder} is not readable: {Error}", folder, exc.Message);
            outp.Error = $"{exc.GetType().Name}: {exc.Message}";
            return outp;
        }
        outp.Found = files.Count;
        security ??= WinSec.Default;
        if (files.Count > 0 && Inbox.FolderProblem(folder, security) is { } bad)
        {
            Log.Logger.LogError("Login folder: {Problem}", bad);
            outp.Error = bad;
            return outp;
        }
        var index = Inbox.ComputerIndex(store, settings.StaleDays);
        var sids = Inbox.SidIndex(store);
        var per = new Dictionary<string, List<JsonNode?>>();
        var done = new List<string>();
        var local = new List<string>();
        foreach (var path in files)
        {
            var name = Path.GetFileName(path);
            string computer;
            JsonObject ev;
            try
            {
                (computer, ev) = ParseEntry(Inbox.ReadCapped(path, MaxBytes));
                var known = index.GetValueOrDefault(computer.ToLowerInvariant());
                var why = WinSec.CheckFileOwner(path, computer, allowUsers: false, security,
                                                known is null ? null : sids.GetValueOrDefault(known));
                if (why is not null) throw new FormatException($"not trusted: {why}");
            }
            catch (Exception exc) when (exc is FormatException or InvalidDataException)
            {
                outp.Failed++;
                Log.Logger.LogWarning("Login file {Name} is not valid ({Error}); renamed to .bad", name, exc.Message);
                try { File.Move(path, Path.ChangeExtension(path, ".bad")); }
                catch (Exception mexc) when (mexc is IOException or UnauthorizedAccessException) { Log.Logger.LogDebug(mexc, "rename failed"); }
                continue;
            }
            catch (IOException exc) when (Busy(exc))
            {
                if (Log.Logger.IsEnabled(LogLevel.Debug)) Log.Logger.LogDebug("Login file {Name} is still being written; read next time", name);
                continue;
            }
            catch (Exception exc) when (exc is IOException or UnauthorizedAccessException)
            {
                outp.Failed++;
                Log.Logger.LogWarning("Login file {Name} could not be read: {Error}", name, exc.Message);
                continue;
            }
            if (IsLocalAccount(computer, ev))                  // e.g. written by an older script: dropped, not stored
            {
                local.Add(path);
                continue;
            }
            if (!index.TryGetValue(computer.ToLowerInvariant(), out var guid))
            {
                outp.Unknown++;
                continue;
            }
            if (!per.TryGetValue(guid, out var list)) per[guid] = list = [];
            list.Add(ev);
            done.Add(path);
        }
        foreach (var (guid, events) in per) store.AddLogons(guid, events);
        foreach (var path in local)
        {
            try { File.Delete(path); outp.Local++; }
            catch (Exception exc) when (exc is IOException or UnauthorizedAccessException)
            {
                Log.Logger.LogWarning("Login file {Name} (local account) could not be deleted: {Error}", Path.GetFileName(path), exc.Message);
            }
        }
        foreach (var path in done)
        {
            try
            {
                File.Delete(path);
                outp.Imported++;
            }
            catch (Exception exc) when (exc is IOException or UnauthorizedAccessException)
            {
                Log.Logger.LogWarning("Login file {Name} was read but could not be deleted: {Error}", Path.GetFileName(path), exc.Message);
            }
        }
        if (outp.Imported > 0 || outp.Failed > 0)
            store.Log("logins", I18n.T("log.logins", ("imported", outp.Imported), ("found", outp.Found),
                                       ("unknown", outp.Unknown), ("failed", outp.Failed)));
        return outp;
    }
}
